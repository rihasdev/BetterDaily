import { test, expect } from '@playwright/test'

test('onboarding, navigation, local settings and offline shell',async({page,context})=>{
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Welcome to BetterDaily.'})).toBeVisible()
  await expect(page.getByRole('checkbox',{name:'Enable optional Islamic lifestyle mode'})).not.toBeChecked()
  await page.getByRole('button',{name:'Get started'}).click()
  await expect(page.getByRole('heading',{name:'A fresh start.'})).toBeVisible()
  await page.getByRole('button',{name:'Goals',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Goals',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Settings',exact:true}).click()
  const faithToggle=page.getByRole('checkbox',{name:'Islamic lifestyle mode'})
  await expect(faithToggle).not.toBeChecked()
  // Controlled input reflects the committed IndexedDB value only after the async save.
  // click() performs the action; the retrying assertions verify the final state.
  await faithToggle.click()
  await expect(faithToggle).toBeChecked()
  await expect(faithToggle).toBeEnabled()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByLabel('Appearance').selectOption('dark')
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark')
  await page.reload()
  await expect(page.getByRole('heading',{name:'Islamic lifestyle mode'})).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark')
  await page.evaluate(async()=>{await navigator.serviceWorker.ready})
  await page.reload()
  await expect.poll(()=>page.evaluate(()=>!!navigator.serviceWorker.controller)).toBe(true)
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByRole('heading',{name:'A fresh start.'})).toBeVisible()
  await expect(page.getByRole('heading',{name:'Islamic lifestyle mode'})).toBeVisible()
})
