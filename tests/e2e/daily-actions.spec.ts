import { test, expect } from '@playwright/test'

test('life vision and affirmation survive reload and offline edits',async({page,context})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'Get started'}).click()
  await expect(page.getByRole('heading',{name:'A fresh start.'})).toBeVisible()
  await page.getByRole('button',{name:'Goals',exact:true}).click()
  await page.getByRole('button',{name:'Edit categories'}).click()
  const family=page.locator('form').filter({has:page.getByRole('heading',{name:'Relationships & family',exact:true})})
  await family.getByLabel('Category name').fill('My family')
  await family.getByLabel('What do I want in this area?').fill('Make time for the people I love.')
  await family.getByRole('button',{name:'Save category'}).click()
  await expect(page.getByRole('status').filter({hasText:'Saved on this device.'})).toBeVisible()
  await page.getByRole('button',{name:'View my vision'}).click()
  await expect(page.getByRole('heading',{name:'My family'})).toBeVisible()
  await page.getByRole('button',{name:'Today',exact:true}).click()
  await page.getByRole('button',{name:'Edit affirmation'}).click()
  await page.getByLabel('Your affirmation').fill('One meaningful action at a time.')
  await page.getByRole('button',{name:'Save affirmation'}).click()
  await expect(page.getByRole('heading',{name:'One meaningful action at a time.'})).toBeVisible()
  await page.getByRole('button',{name:'Acknowledge today'}).click()
  await expect(page.getByRole('button',{name:'Undo check-in'})).toBeEnabled()
  await page.evaluate(async()=>{await navigator.serviceWorker.ready})
  await page.reload()
  await expect.poll(()=>page.evaluate(()=>!!navigator.serviceWorker.controller)).toBe(true)
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByRole('heading',{name:'One meaningful action at a time.'})).toBeVisible()
  await page.getByRole('button',{name:'Undo check-in'}).click()
  await expect(page.getByRole('button',{name:'Acknowledge today'})).toBeEnabled()
  await page.getByRole('button',{name:'Goals',exact:true}).click()
  await expect(page.getByText('Make time for the people I love.')).toBeVisible()
  await page.getByRole('button',{name:'Edit categories'}).click()
  const saved=page.locator('form').filter({has:page.getByRole('heading',{name:'My family',exact:true})})
  await saved.getByLabel('What do I want in this area?').fill('Spend Sunday with family.')
  await saved.getByRole('button',{name:'Save category'}).click()
  await expect(saved.getByRole('status')).toHaveText('Saved on this device.')
  await page.reload()
  await page.getByRole('button',{name:'Goals',exact:true}).click()
  await expect(page.getByText('Spend Sunday with family.')).toBeVisible()
})
