import { test, expect } from '@playwright/test'

test('track quantities, custom habits, priorities and history offline',async({page,context})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'Get started'}).click()
  const water=page.getByRole('article',{name:'Water',exact:true})
  await expect(water.getByText('0 / 250 mL')).toBeVisible()
  await water.getByRole('button',{name:'Add Water 100 mL'}).click()
  await expect(water.getByText('100 / 250 mL')).toBeVisible()
  await water.getByRole('button',{name:'Add Water 150 mL'}).click()
  await expect(water.getByText('250 / 250 mL')).toBeVisible()
  await expect(water.getByText('Completed',{exact:true})).toBeVisible()
  await water.getByText('Manage entries (2)').click()
  await water.getByRole('button',{name:'Delete Water 100 mL'}).click()
  await expect(water.getByText('150 / 250 mL')).toBeVisible()
  await expect(water.getByText('Open',{exact:true})).toBeVisible()
  await page.getByLabel('Priority 1',{exact:true}).fill('Practise DAX')
  await page.getByLabel('Link priority 1 to a goal').selectOption('career')
  await page.getByRole('button',{name:'Save priority 1'}).click()
  await page.getByRole('button',{name:'Complete priority 1',exact:true}).click()
  await expect(page.getByRole('button',{name:'Undo priority 1',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Settings',exact:true}).click()
  await page.getByRole('button',{name:'Add custom habit'}).click()
  const form=page.getByRole('form',{name:'New custom habit'})
  await form.getByLabel('Habit name').fill('Read a page')
  await form.getByLabel('Routine period').selectOption('Evening')
  await form.getByLabel("Apply to today's plan too").click()
  await form.getByRole('button',{name:'Create custom habit'}).click()
  await expect(form).toHaveCount(0)
  await page.getByRole('button',{name:'Today',exact:true}).click()
  const custom=page.getByRole('article',{name:'Read a page',exact:true})
  await custom.getByRole('button',{name:'Mark complete'}).click()
  await expect(custom.getByRole('button',{name:'Undo completion'})).toBeVisible()
  await page.evaluate(async()=>{await navigator.serviceWorker.ready})
  await page.reload()
  await expect.poll(()=>page.evaluate(()=>!!navigator.serviceWorker.controller)).toBe(true)
  await context.setOffline(true)
  await page.reload()
  await expect(water.getByText('150 / 250 mL')).toBeVisible()
  await water.getByRole('button',{name:'Add Water 100 mL'}).click()
  await expect(water.getByText('250 / 250 mL')).toBeVisible()
  await page.getByRole('button',{name:'Progress',exact:true}).click()
  const yesterday=await page.evaluate(()=>{
    const d=new Date();d.setDate(d.getDate()-1)
    const pad=(n:number)=>String(n).padStart(2,'0')
    return [d.getFullYear(),pad(d.getMonth()+1),pad(d.getDate())].join('-')
  })
  await page.getByLabel('View date').fill(yesterday)
  await expect(water.getByText('0 / 250 mL')).toBeVisible()
  await water.getByRole('button',{name:'Add Water 100 mL'}).click()
  await expect(water.getByText('100 / 250 mL')).toBeVisible()
  await page.getByRole('button',{name:'Back to today'}).click()
  await expect(water.getByText('250 / 250 mL')).toBeVisible()
  await expect(page.getByLabel('Priority 1',{exact:true})).toHaveValue('Practise DAX')
  await expect(custom.getByRole('button',{name:'Undo completion'})).toBeVisible()
})
